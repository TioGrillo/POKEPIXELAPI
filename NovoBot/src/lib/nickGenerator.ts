/**
 * Gera um nick único, expressivo e otimizado para a limitação de 16 caracteres.
 */
export function generateNick(
  gender: 'male' | 'female' = 'male',
  options: {
    usePrefix?: boolean;
    prefix?: string;
    avoidNumbers?: boolean;
  } = {}
): string {
  const { usePrefix = false, prefix = '', avoidNumbers = false } = options;

  const isMale = gender === 'male';
  const baseList = isMale ? MALE_NAMES : FEMALE_NAMES;
  const prefixList = isMale ? MALE_PREFIXES : FEMALE_PREFIXES;
  const suffixList = isMale ? MALE_SUFFIXES : FEMALE_SUFFIXES;
  
  // Seleciona um nome base aleatório da lista
  let baseName = baseList[Math.floor(Math.random() * baseList.length)];

  // Escolhe prefixo (do campo customizado do usuário ou sorteado da lista do sexo)
  let chosenPrefix = '';
  if (usePrefix) {
    if (prefix && prefix.trim().length > 0) {
      chosenPrefix = prefix.trim().replace(/\s+/g, '');
    } else {
      chosenPrefix = prefixList[Math.floor(Math.random() * prefixList.length)];
    }
  }

  // 40% de chance de adicionar sufixo específico do sexo se couber
  let chosenSuffix = '';
  if (Math.random() > 0.6) {
    chosenSuffix = suffixList[Math.floor(Math.random() * suffixList.length)];
  }

  // Monta o nome tentando ajustar tudo dentro dos 16 caracteres do servidor
  let finalNick = `${chosenPrefix}${baseName}${chosenSuffix}`;

  // Se ficou muito longo (> 14 para caber número ou > 16 limpo), remove o sufixo
  if (finalNick.length > 14 && chosenSuffix) {
    finalNick = `${chosenPrefix}${baseName}`;
  }

  // Se NÃO for para evitar números, adiciona um sufixo numérico curto aleatório (1 a 99)
  if (!avoidNumbers) {
    const num = Math.floor(Math.random() * 99) + 1;
    finalNick = `${finalNick}${num}`;
  }

  // Garante o limite estrito de 16 caracteres do PokePixel
  if (finalNick.length > 16) {
    finalNick = finalNick.substring(0, 16);
  }

  return finalNick;
}

/**
 * Gera um lote de nicks únicos
 */
export function generateNickBatch(
  count: number,
  gender: 'male' | 'female',
  options: {
    usePrefix?: boolean;
    prefix?: string;
    avoidNumbers?: boolean;
  } = {}
): string[] {
  const nicks = new Set<string>();
  let attempts = 0;
  
  while (nicks.size < count && attempts < count * 10) {
    attempts++;
    const nick = generateNick(gender, options);
    if (nick.length >= 3 && nick.length <= 16) {
      nicks.add(nick);
    }
  }
  
  return Array.from(nicks);
}
